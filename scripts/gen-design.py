#!/usr/bin/env python3
"""Writes docs/DESIGN.md: every named size, font, motion value and colour of the shell, read from
quickshell/MenuStyle.qml and quickshell/theme/themes.json, so the doc can't drift from the code.

  python3 scripts/gen-design.py            rewrite docs/DESIGN.md
  python3 scripts/gen-design.py --check    exit 1 if docs/DESIGN.md is stale (scripts/check.py runs this)
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "DESIGN.md"
PROP = re.compile(r"^    readonly property (\w+) (\w+):\s*(.*?)\s*(?://\s*(.*))?$")
ROLES = ("base", "shadow", "highlight", "accent", "text", "outline", "urgent")

sys.path.insert(0, str(ROOT / "quickshell" / "theme"))
import apply as A  # noqa: E402  (contrast; same maths the palette check uses)


def parse_menustyle():
    rows = []
    for line in (ROOT / "quickshell" / "MenuStyle.qml").read_text(encoding="utf-8").splitlines():
        m = PROP.match(line)
        if not m:
            continue
        typ, name, value, note = m.group(1), m.group(2), m.group(3), m.group(4) or ""
        if value.endswith("{"):
            value = "(computed)"
        rows.append((typ, name, value, note))
    return rows


def group_of(typ, name):
    if re.fullmatch(r"space\d+|pad|gap", name) or re.search(r"(Pad|Gap|Inset|Spacing)$", name):
        return "Spacing"
    if name.startswith("anim") or name in ("reduceMotion", "notificationFade", "idleDimFade"):
        return "Motion"
    if re.search(r"[Ff]ont|^iconSize|IconSize|Glyph$", name) or name in ("fontSize", "iconSize"):
        return "Fonts and icons"
    if typ == "color":
        return "Derived colours"
    if typ in ("int", "real"):
        return "Sizes and timings"
    return "Other"


def cell(s):
    return s.replace("|", "\\|")


def themes_table():
    themes = json.loads((ROOT / "quickshell" / "theme" / "themes.json").read_text(encoding="utf-8"))
    head = "| theme | " + " | ".join(ROLES) + " | edge | text / base |"
    lines = [head, "|" + "---|" * (len(ROLES) + 3)]
    for name, p in themes.items():
        cols = " | ".join("`%s`" % p[r] for r in ROLES)
        edge = A.contrast(p["base"], p["highlight"])
        tb = A.contrast(p["text"], p["base"])
        lines.append(f"| {name} | {cols} | {edge:.2f} | {tb:.1f} |")
    return "\n".join(lines)


def build():
    groups = {}
    for typ, name, value, note in parse_menustyle():
        groups.setdefault(group_of(typ, name), []).append((typ, name, value, note))
    out = [
        "# Design tokens",
        "",
        "<!-- Generated by scripts/gen-design.py from quickshell/MenuStyle.qml and quickshell/theme/themes.json."
        " Do not edit: change the source, then run `python3 scripts/gen-design.py`. scripts/check.py fails when this file is stale. -->",
        "",
        "Every named size, font, motion value and colour. The rules are in `CLAUDE.md` (Theme, Design rules);"
        " this is only the numbers. Values are shown as written in MenuStyle.qml, so a name that points at another name shows that name.",
        "",
        "## Palettes (`quickshell/theme/themes.json`)",
        "",
        "`edge` is the contrast from `base` to `highlight` (the bevel's light edge, at least %.2f), `text / base` the text contrast (at least %.1f)."
        % (A.MIN_EDGE, A.MIN_TEXT),
        "",
        themes_table(),
        "",
    ]
    for g in ("Spacing", "Fonts and icons", "Motion", "Sizes and timings", "Derived colours", "Other"):
        rows = groups.get(g)
        if not rows:
            continue
        out += [f"## {g}", "", "| name | type | value | note |", "|---|---|---|---|"]
        for typ, name, value, note in rows:
            out.append(f"| `{name}` | {typ} | `{cell(value)}` | {cell(note)} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    text = build()
    if "--check" in sys.argv[1:]:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if have != text:
            print("docs/DESIGN.md is stale: run python3 scripts/gen-design.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
